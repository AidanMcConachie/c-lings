#ifndef CLINGS_COMMON_H
#define CLINGS_COMMON_H

#include <stdbool.h>
#include <stddef.h>
#include <stdio.h>

#define CLINGS_VERSION "1.0.0"
#define STATE_FILE ".clings-state.txt"
#define WORK_DIR ".clings"
#define BUILD_DIR ".clings/build"

/* ---- util.c ---------------------------------------------------------- */

typedef struct {
    char *data;
    size_t len, cap;
} Buf;

void buf_append(Buf *b, const char *s, size_t n);
void buf_puts(Buf *b, const char *s);
void buf_printf(Buf *b, const char *fmt, ...) __attribute__((format(printf, 2, 3)));
void buf_clear(Buf *b);
void buf_free(Buf *b);

void *xmalloc(size_t n);
void *xrealloc(void *p, size_t n);
char *xstrdup(const char *s);
char *xasprintf(const char *fmt, ...) __attribute__((format(printf, 1, 2)));
_Noreturn void die(const char *fmt, ...) __attribute__((format(printf, 1, 2)));

bool read_file(const char *path, Buf *out);
bool write_file(const char *path, const char *data, size_t len);
bool mkdir_p(const char *path);
bool file_exists(const char *path);
bool dir_exists(const char *path);
long long file_mtime_ns(const char *path);

/* ---- term.c ---------------------------------------------------------- */

extern bool color_enabled;

#define C_RESET  (color_enabled ? "\x1b[0m" : "")
#define C_BOLD   (color_enabled ? "\x1b[1m" : "")
#define C_DIM    (color_enabled ? "\x1b[2m" : "")
#define C_RED    (color_enabled ? "\x1b[31m" : "")
#define C_GREEN  (color_enabled ? "\x1b[32m" : "")
#define C_YELLOW (color_enabled ? "\x1b[33m" : "")
#define C_BLUE   (color_enabled ? "\x1b[34m" : "")
#define C_CYAN   (color_enabled ? "\x1b[36m" : "")
#define C_REV    (color_enabled ? "\x1b[7m" : "")

enum {
    KEY_NONE = -1,
    KEY_ESC = 27,
    KEY_ENTER = 1000,
    KEY_UP,
    KEY_DOWN,
    KEY_PGUP,
    KEY_PGDN,
    KEY_HOME,
    KEY_END,
};

void term_init(void);
void term_raw_enable(void);
void term_raw_disable(void);
int term_read_key(int timeout_ms);
void term_size(int *rows, int *cols);
void term_clear(void);
void term_alt_screen(bool on);

/* ---- info.c ---------------------------------------------------------- */

typedef struct {
    char *name;
    char *dir;
    char *hint;
    bool test;
    bool skip_check_unsolved;
    char *path;     /* exercises/<dir>/<name>.c */
    char *sol_path; /* solutions/<dir>/<name>.c */
    bool done;
} Exercise;

typedef struct {
    Exercise *items;
    size_t len;
    char *welcome;
    char *final_msg;
} Info;

bool info_parse(const char *src, size_t len, Info *info, char *err, size_t errlen);
Exercise *info_find(Info *info, const char *name);

/* ---- state.c --------------------------------------------------------- */

typedef struct {
    Info info;
    size_t current;
    bool fresh; /* no state file existed yet */
} App;

void state_load(App *app);
bool state_save(const App *app);
size_t app_done_count(const App *app);
size_t app_next_pending(const App *app, size_t from); /* returns info.len if none */
void app_set_current(App *app, size_t idx);
Exercise *app_current(App *app);
bool app_mark_done(App *app, Exercise *ex);
bool app_reset_exercise(App *app, Exercise *ex, char *err, size_t errlen);

/* ---- embedded (generated by src/embed.c) ----------------------------- */

typedef struct {
    const char *path;
    const unsigned char *data;
    size_t len;
} EmbeddedFile;

extern const EmbeddedFile embedded_files[];
extern const size_t embedded_files_len;
const EmbeddedFile *embedded_find(const char *path);

/* ---- runner.c -------------------------------------------------------- */

typedef enum {
    RES_PASS,
    RES_COMPILE_ERROR,
    RES_FAIL,
    RES_CRASH,
    RES_TIMEOUT,
    RES_INTERNAL,
} RunResult;

void runner_prepare(void);
RunResult run_source(const Exercise *ex, const char *src_path, const char *bin_name, Buf *out);
void runner_kill_child(void);

/* Runs every exercise in parallel, updating each `done` flag. */
size_t check_all(App *app, bool show_progress);

/* ---- watch.c / list.c ------------------------------------------------ */

int cmd_watch(App *app);
bool list_ui(App *app); /* returns true if the current exercise changed */
void print_progress_bar(size_t done, size_t total, int cols);

#endif
