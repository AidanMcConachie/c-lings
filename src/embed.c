/*
 * Build-time tool: turns files into a C source with their contents, so the
 * clings binary can reset exercises and `init` new directories on its own.
 *
 * Usage: embed OUTPUT.c FILE...
 */
#include <stdio.h>
#include <stdlib.h>

int main(int argc, char **argv) {
    if (argc < 2) {
        fprintf(stderr, "usage: %s OUTPUT.c FILE...\n", argv[0]);
        return 2;
    }
    FILE *out = fopen(argv[1], "w");
    if (!out) {
        perror(argv[1]);
        return 1;
    }
    fprintf(out, "/* Generated by src/embed.c - do not edit. */\n#include \"common.h\"\n\n");

    size_t *lens = calloc((size_t)argc, sizeof *lens);
    for (int i = 2; i < argc; i++) {
        FILE *in = fopen(argv[i], "rb");
        if (!in) {
            perror(argv[i]);
            return 1;
        }
        fprintf(out, "static const unsigned char file_%d[] = {", i - 2);
        int c;
        size_t n = 0;
        while ((c = fgetc(in)) != EOF) {
            fprintf(out, "%s0x%02x,", n % 16 == 0 ? "\n    " : "", c);
            n++;
        }
        fprintf(out, "\n    0x00\n};\n\n");
        lens[i] = n;
        fclose(in);
    }

    fprintf(out, "const EmbeddedFile embedded_files[] = {\n");
    for (int i = 2; i < argc; i++) {
        fputs("    {\"", out);
        for (const char *p = argv[i]; *p; p++) {
            if (*p == '"' || *p == '\\') fputc('\\', out);
            fputc(*p, out);
        }
        fprintf(out, "\", file_%d, %zu},\n", i - 2, lens[i]);
    }
    if (argc == 2) fputs("    {0},\n", out);
    fprintf(out, "};\n\nconst size_t embedded_files_len = %d;\n", argc - 2);
    free(lens);
    return fclose(out) == 0 ? 0 : 1;
}
